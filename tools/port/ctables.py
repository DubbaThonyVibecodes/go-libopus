#!/usr/bin/env python3
"""Convert upstream silk table files (const arrays) to Go.

Usage: ctables.py <src.c> <out.go> [--flatten NAME ...]

Handles N-dimensional const integer arrays, scalar consts, pointer tables,
and the two silk_NLSF_CB_struct initialisers. Identifiers used in
dimensions or values (macros) are kept verbatim; the Go package defines
them as constants.
"""
import re, sys

TYPES = {'opus_uint8': 'uint8', 'opus_int8': 'int8', 'opus_int16': 'int16', 'opus_int32': 'int32'}

def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return s

def goname(n):
    return n[5:] if n.startswith('silk_') else n

def split_top(s, sep=','):
    """split on sep at paren/brace depth 0"""
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '({[':
            depth += 1
        elif ch in ')}]':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]

def parse_init(s):
    """parse a C brace initializer into nested lists of leaf strings"""
    s = s.strip()
    assert s[0] == '{' and s[-1] == '}', s[:40]
    inner = s[1:-1]
    items = split_top(inner)
    return [parse_init(it) if it.startswith('{') else re.sub(r'\s+', ' ', it) for it in items]

def emit(node, depth):
    """emit nested list as Go composite literal body lines"""
    ind = '\t' * depth
    if all(isinstance(x, str) for x in node):
        lines = []
        for i in range(0, len(node), 16):
            lines.append(ind + ', '.join(node[i:i+16]) + ',')
        return lines
    lines = []
    for child in node:
        if isinstance(child, str):
            lines.append(ind + child + ',')
        else:
            lines.append(ind + '{')
            lines.extend(emit(child, depth + 1))
            lines.append(ind + '},')
    return lines

def main():
    src, out = sys.argv[1], sys.argv[2]
    flatten = set()
    if '--flatten' in sys.argv:
        flatten = set(sys.argv[sys.argv.index('--flatten')+1:])
    text = strip_comments(open(src).read())
    body = []
    decls = re.finditer(
        r'(?:static\s+)?(?:silk_DWORD_ALIGN\s+)?const\s+(?P<type>opus_u?int(?:8|16|32)|silk_NLSF_CB_struct)\s*(?P<ptr>\*\s*const\s+)?(?P<name>silk_\w+)\s*(?P<dims>(?:\s*\[[^\]]*\])*)\s*=\s*(?P<init>\{.*?\}|[^;{]+);',
        text, flags=re.S)
    for m in decls:
        ctype, ptr, name, dims, init = m.group('type'), m.group('ptr'), m.group('name'), m.group('dims'), m.group('init').strip()
        dimlist = [re.sub(r'\s+', ' ', d.strip()) for d in re.findall(r'\[([^\]]*)\]', dims)]
        if ctype == 'silk_NLSF_CB_struct':
            fields = split_top(init.strip()[1:-1])
            fx = lambda e: re.sub(r'SILK_FIX_CONST\(\s*([^,]+?)\s*,\s*(\d+)\s*\)', r'SILK_FIX_CONST(\1, \2)', e)
            body.append(f'var {goname(name)} = NLSFCBStruct{{\n'
                        f'\tnVectors: {fields[0]},\n\torder: {fields[1]},\n'
                        f'\tquantStepSize_Q16: int16({fx(fields[2])}),\n'
                        f'\tinvQuantStepSize_Q6: int16({fx(fields[3])}),\n'
                        f'\tCB1_NLSF_Q8: {goname(fields[4])}[:],\n\tCB1_iCDF: {goname(fields[5])}[:],\n'
                        f'\tpred_Q8: {goname(fields[6])}[:],\n\tec_sel: {goname(fields[7])}[:],\n'
                        f'\tec_iCDF: {goname(fields[8])}[:],\n\tec_Rates_Q5: {goname(fields[9])}[:],\n'
                        f'\tdeltaMin_Q15: {goname(fields[10])}[:],\n}}\n')
            continue
        gotype = TYPES[ctype]
        if ptr:
            entries = split_top(init.strip()[1:-1])
            ents = [goname(re.search(r'(silk_\w+)', e).group(1)) + '[:]' for e in entries]
            body.append(f'var {goname(name)} = [{dimlist[0]}][]{gotype}{{\n\t' + ',\n\t'.join(ents) + ',\n}\n')
            continue
        if not dimlist:
            body.append(f'const {goname(name)} {gotype} = {init}\n')
            continue
        if name in flatten:
            nums = re.findall(r'-?\d+', init)
            dimexpr = ' * '.join(f'({d})' for d in dimlist)
            lines = ['\t' + ', '.join(nums[i:i+16]) + ',' for i in range(0, len(nums), 16)]
            body.append(f'// flattened from {name}{dims}: used through a flat pointer in C\nvar {goname(name)} = [{dimexpr}]{gotype}{{\n' + '\n'.join(lines) + '\n}\n')
            continue
        node = parse_init(init)
        lines = emit(node, 1)
        body.append(f'var {goname(name)} = [' + ']['.join(dimlist) + f']{gotype}{{\n' + '\n'.join(lines) + '\n}\n')
    header = f'package silk\n\n// Code generated by tools/port/ctables.py from upstream silk/{src.split("/")[-1]}; DO NOT EDIT.\n\n'
    open(out, 'w').write(header + '\n'.join(body))

main()
